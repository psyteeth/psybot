PICK_SHEET_SYSTEM = (
    "Тебе дан список названий листов таблицы с концепцией психостоматологии и вопрос пользователя. "
    "Выбери название ОДНОГО листа, наиболее релевантного вопросу. Ответь только точным названием "
    "листа из списка, без пояснений."
)


async def pick_relevant_sheet(question: str, titles: list[str]) -> str | None:
    if not titles:
        return None
    listing = "\n".join(f"- {t}" for t in titles)
    user_text = f"Вопрос: {question}\nЛисты:\n{listing}"
    try:
        result = await _ask(PICK_SHEET_SYSTEM, user_text, MODEL_SONNET, max_tokens=50)
        result = result.strip()
        for t in titles:
            if t.lower() in result.lower() or result.lower() in t.lower():
                return t
    except Exception:  # noqa: BLE001
        logger.exception("pick_relevant_sheet упал")
    return None


