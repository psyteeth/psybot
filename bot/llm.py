async def analyze_self_serving_edit(summary: str, addition: str) -> dict:
    user_text = f"Пересказ истории, который показали пользователю:\n{summary}\n\nЧто добавил пользователь:\n{addition}"
    try:
        raw = await _ask(SELF_SERVING_EDIT_SYSTEM, user_text, MODEL_SONNET, max_tokens=300)
        data = json.loads(_strip_code_fence(raw))
        return {
            "self_serving": bool(data.get("self_serving", False)),
            "hidden_need": str(data.get("hidden_need", "")).strip(),
            "punchline": str(data.get("punchline", "")).strip(),
        }
    except Exception:  # noqa: BLE001
        logger.exception("analyze_self_serving_edit упал/не распарсился")
        return {"self_serving": False, "hidden_need": "", "punchline": ""}
