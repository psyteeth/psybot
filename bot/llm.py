def _strip_code_fence(raw: str) -> str:
    """Достаёт JSON из ответа модели устойчиво к обёртке в ```код``` И к тому, что модель
    дописывает пояснение ПОСЛЕ JSON, несмотря на просьбу отвечать строго JSON — живой баг:
    Haiku на classify_concrete_answer вернула корректный JSON с target=self, но следом
    дописала "**Обоснование:** ...", из-за чего json.loads падал на "Extra data" и
    классификатор проваливался в safe-default, который ИНВЕРТИРОВАЛ верный вердикт модели
    (self → пропущено как other). Ищем первую сбалансированную JSON-структуру ({...} или
    [...]) в тексте и возвращаем только её, что бы ни было до и после."""
    raw = raw.strip()
    start = next((i for i, ch in enumerate(raw) if ch in "{["), None)
    if start is None:
        return raw
    open_ch = raw[start]
    close_ch = "}" if open_ch == "{" else "]"
    depth = 0
    in_string = False
    escape = False
    for i in range(start, len(raw)):
        ch = raw[i]
        if in_string:
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch == open_ch:
            depth += 1
        elif ch == close_ch:
            depth -= 1
            if depth == 0:
                return raw[start : i + 1]
    return raw[start:]


