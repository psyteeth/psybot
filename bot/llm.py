async def classify_secret_gate(question: str, recent_context: str, candidates: list[dict]) -> dict:
    candidates_block = "\n\n".join(
        f"chunk_id: {c['chunk_id']}\nстатус: {c['status'] or 'без статуса'}\nтекст: {c['text'][:400]}"
        for c in candidates
    )
    user_text = (
        f"Вопрос клиента: {question}\n\nПоследние реплики разговора:\n{recent_context}\n\n"
        f"Кандидаты:\n{candidates_block}"
    )
    try:
        raw = await _ask(SECRET_GATE_SYSTEM, user_text, MODEL_HAIKU, max_tokens=150)
        data = json.loads(_strip_code_fence(raw))
        chunk_id = data.get("chunk_id")
        share = bool(data.get("share", False)) and bool(chunk_id)
        return {"share": share, "chunk_id": chunk_id if share else None, "why": str(data.get("why", ""))}
    except Exception:  # noqa: BLE001
        logger.exception("classify_secret_gate упал/не распарсился")
        # безопасный дефолт при сбое — НЕ делиться (в отличие от других классификаторов, здесь
        # молчание безопаснее, чем случайно вывалить секрет не по месту)
        return {"share": False, "chunk_id": None, "why": ""}


