TOOTH_PARSE_SYSTEM = (
    "Ты помогаешь определить номер зуба по схеме FDI (11-18, 21-28, 31-38, 41-48) "
    "из свободного описания пользователя на русском языке (например «верхний передний слева», "
    "«нижняя шестёрка справа»). Отвечай ТОЛЬКО числом от 11 до 48, которое является "
    "валидным номером по схеме FDI. Если однозначно определить нельзя — ответь: unknown."
)


async def parse_tooth_number(text: str) -> int | None:
    try:
        result = await _ask(TOOTH_PARSE_SYSTEM, text, MODEL_HAIKU, max_tokens=10)
        digits = "".join(ch for ch in result if ch.isdigit())
        if digits:
            return int(digits)
    except Exception:  # noqa: BLE001
        logger.exception("parse_tooth_number упал")
    return None


DIAGNOSIS_SUBJECT_SYSTEM = (
    "Ты классификатор для ветки «Зубы» психостоматологического бота. Пользователь описывает, что "
    "самое страшное может случиться с зубом. Определи по тексту, о ком идёт речь:\n"
    '- "self" — пользователь описывает СВОЙ собственный зуб/свои ощущения.\n'
    '- "other" — пользователь явно описывает ситуацию ДРУГОГО человека («у дочери», «у сына», «у '
    'него», «моя мама» и т.п.) — то есть проходит диагностику ЗА кого-то другого, не за себя.\n\n'
    "Если \"other\" — определи ещё:\n"
    '- "subject_age": "minor" (явно ребёнок/подросток, самостоятельно диагностику пройти не может), '
    '"adult" (явно взрослый — партнёр, родитель, коллега и т.п.), или "unclear" (не ясно).\n'
    '- "motivation": "curious" (любопытство, играючи, без напряжения в тексте), "anxious" (тревога, '
    'вина, беспокойство за другого), или "unclear".\n\n'
    'Ответь СТРОГО валидным JSON без markdown: {"subject": "self" или "other", "subject_age": '
    '"minor" или "adult" или "unclear", "motivation": "curious" или "anxious" или "unclear"}. Если '
    'subject="self" — subject_age и motivation = "unclear".'
)


async def classify_diagnosis_subject(text: str) -> dict:
    try:
        raw = await _ask(DIAGNOSIS_SUBJECT_SYSTEM, text, MODEL_HAIKU, max_tokens=80)
        data = json.loads(_strip_code_fence(raw))
        subject = data.get("subject")
        if subject not in ("self", "other"):
            subject = "self"
        subject_age = data.get("subject_age")
        if subject_age not in ("minor", "adult", "unclear"):
            subject_age = "unclear"
        motivation = data.get("motivation")
        if motivation not in ("curious", "anxious", "unclear"):
            motivation = "unclear"
        return {"subject": subject, "subject_age": subject_age, "motivation": motivation}
    except Exception:  # noqa: BLE001
        logger.exception("classify_diagnosis_subject упал/не распарсился")
        return {"subject": "self", "subject_age": "unclear", "motivation": "unclear"}


