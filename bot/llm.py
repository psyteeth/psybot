GENDER_HINT_SYSTEM = (
    "Определи, если это вообще возможно, грамматический род, которым человек описывает СЕБЯ в тексте "
    "— по глаголам и прилагательным прошедшего времени о себе («я сделал» vs «я сделала», «я сам» vs "
    "«я сама», «обиделся» vs «обиделась» и т.п.). Ответь ровно одним словом: masc — если есть чёткие "
    "мужские формы; fem — если есть чёткие женские формы; unknown — если признаков нет или текст "
    "слишком короткий/неоднозначный. Не гадай — если сомневаешься, отвечай unknown."
)


async def detect_gender_hint(text: str) -> str:
    try:
        result = await _ask(GENDER_HINT_SYSTEM, text, MODEL_HAIKU, max_tokens=10)
        result = result.lower().strip()
        if "masc" in result:
            return "masc"
        if "fem" in result:
            return "fem"
    except Exception:  # noqa: BLE001
        logger.exception("detect_gender_hint упал")
    return "unknown"


