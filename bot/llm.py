MENU_SYSTEM = (
    "Ты классификатор намерений в Telegram-боте психостоматологии. "
    "Пользователь написал свободный текст вместо нажатия кнопки. "
    "Ответь ровно одним словом: relationships (если про отношения/людей/конфликт), "
    "teeth (если про зубы/боль), concept (если спрашивает про саму концепцию/метод), "
    "greeting (если это приветствие или неясно)."
)


async def classify_menu_intent(text: str) -> str:
    try:
        result = await _ask(MENU_SYSTEM, text, MODEL_HAIKU, max_tokens=10)
        result = result.lower().strip()
        for opt in ("relationships", "teeth", "concept", "greeting"):
            if opt in result:
                return opt
    except Exception:  # noqa: BLE001
        logger.exception("classify_menu_intent упал")
    return "greeting"


