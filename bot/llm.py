E_SHIFT_SYSTEM = (
    "Бот только что честно спросил пользователя психостоматологического бота, изменилось ли что-то в "
    "ощущении его долженствования после восьми вопросов-оспариваний, или всё осталось так же, как "
    "раньше. Определи по ответу пользователя:\n"
    '- "improved" — явно говорит, что стало легче/по-другому/задевает меньше/что-то сдвинулось.\n'
    '- "same_or_worse" — явно говорит, что ничего не изменилось, или стало хуже/тяжелее/задевает так '
    "же сильно или сильнее.\n"
    '- "unclear" — ответ не даёт понять однозначно, уклоняется, или отвечает не по существу вопроса.\n\n'
    "Ответь СТРОГО одним словом: improved, same_or_worse или unclear."
)


async def classify_e_shift(text: str) -> str:
    try:
        result = await _ask(E_SHIFT_SYSTEM, text, MODEL_HAIKU, max_tokens=10)
        result = result.lower().strip()
        for verdict in ("same_or_worse", "improved", "unclear"):
            if verdict in result:
                return verdict
        return "unclear"
    except Exception:  # noqa: BLE001
        logger.exception("classify_e_shift упал")
        return "unclear"


