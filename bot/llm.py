async def analyze_e_insight(event: str, narrative: str, prior_context: str, latest_answer: str) -> dict:
    user_text = (
        f"Событие (A): {event}\nДолженствование (B): {narrative}\n"
        f"Предыдущий контекст ответа пользователя в этом разборе: {prior_context or '(это первый ответ)'}\n"
        f"Последний ответ пользователя: {latest_answer}"
    )
    try:
        raw = await _ask(E_ANALYZE_SYSTEM, user_text, MODEL_SONNET, max_tokens=200)
        data = json.loads(_strip_code_fence(raw))
        return {
            "has_insight": bool(data.get("has_insight", False)),
            "reflection": str(data.get("reflection", "")).strip(),
        }
    except Exception:  # noqa: BLE001
        logger.exception("analyze_e_insight упал/не распарсился")
        return {"has_insight": False, "reflection": ""}


