from anthropic import AsyncAnthropic

from bot.config import ANTHROPIC_API_KEY, MODEL_HAIKU, MODEL_SONNET

logger = logging.getLogger(__name__)

_client = AsyncAnthropic(api_key=ANTHROPIC_API_KEY) if ANTHROPIC_API_KEY else None

# Пол пользователя бот не спрашивает и не хранит. Добавляется во все промпты,
# где модель обращается к пользователю свободным текстом, чтобы не гадать
# род в глаголах прошедшего времени ("почувствовал" vs "почувствовала").
GENDER_NEUTRAL_RULE = (
    " Пол собеседника неизвестен и не спрашивается: обращайся на «ты», избегай "
    "гендерно-окрашенных форм глаголов прошедшего времени по отношению к нему "
    "(вместо «ты почувствовал/почувствовала» используй настоящее время или "
    "безличные обороты)."
)


async def _ask(system: str, user_text: str, model: str, max_tokens: int = 500) -> str:
    if _client is None:
        raise RuntimeError("ANTHROPIC_API_KEY не задан")
    resp = await _client.messages.create(
        model=model,
        max_tokens=max_tokens,
        system=[{"type": "text", "text": system, "cache_control": {"type": "ephemeral"}}],
        messages=[{"role": "user", "content": user_text}],
        thinking={"type": "disabled"},
    )
    return "".join(block.text for block in resp.content if block.type == "text").strip()


