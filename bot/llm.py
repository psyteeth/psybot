    try:
        raw = await _ask(PUNCHLINE_SYSTEM, user_text, MODEL_SONNET, max_tokens=400)
        data = json.loads(_strip_code_fence(raw))
        return {
            "hidden_need": str(data.get("hidden_need", "")),
            "category": str(data.get("category", "2")),
            "reply": str(data.get("reply", "")).strip(),
        }
    except Exception:  # noqa: BLE001
        logger.exception("generate_punchline упал/не распарсился")
        return {"hidden_need": "", "category": "2", "reply": "Слышу тебя. Продолжим?"}


