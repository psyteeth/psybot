def _cap_sentences(text: str, max_sentences: int = 3) -> str:
    """Предохранитель от того, что модель проигнорирует лимит длины в SIMPLE_MODE_ADDENDUM —
    режет по границе предложения (не по количеству символов), чтобы никогда не обрывать посреди
    слова, даже если модель написала больше, чем просили."""
    text = text.strip()
    parts = re.split(r"(?<=[.!?…])\s+(?=[А-ЯA-ZЁ«\"])", text)
    if len(parts) <= max_sentences:
        return text
    return " ".join(parts[:max_sentences]).strip()


def _trim_incomplete_tail(text: str) -> str:
    """Предохранитель от обрыва ответа посередине предложения/слова, когда модель упёрлась в
    max_tokens (живой баг: ответ перед «Похоже ли это на правду?» обрывался на полуслове). Если
    текст не заканчивается знаком конца предложения — отбрасывает незаконченный хвост по границе
    последнего целого предложения."""
    text = text.strip()
    if not text or text[-1] in ".!?…»\"":
        return text
    parts = re.split(r"(?<=[.!?…])\s+(?=[А-ЯA-ZЁ«\"])", text)
    if len(parts) <= 1:
        return text
    return " ".join(parts[:-1]).strip()


async def answer_concept_question(
    question: str, context_text: str, author_examples: list[dict] | None = None, simple: bool = False,
) -> str:
    examples_block = ""
    if author_examples:
        parts = []
        for e in author_examples:
            part = f"Вопрос: {e['question']}\nОтвет автора: {e['answer']}\nТон: {e['tone']}"
            if e.get("instruction"):
                part += f"\nУказание боту: {e['instruction']}"
            parts.append(part)
        examples_block = (
            "\n\nПохожие вопросы из базы автора (образец тона и подачи, не факты для цитирования):\n\n"
            + "\n\n".join(parts)
        )
    user_text = (
        f"{FOUNDATION_FACT}\n\n{BRIDGE_THEORY_FACT}\n\nФрагменты таблицы концепции:\n{context_text[:CONCEPT_CONTEXT_MAX_CHARS]}"
        f"{examples_block}\n\nВопрос пользователя: {question}"
    )
    system = CONCEPT_SYSTEM + (SIMPLE_MODE_ADDENDUM if simple else EXPLAIN_MODE_ADDENDUM)
    # max_tokens с запасом (не 200) — предохранитель по предложениям режет ЛИШНЕЕ чисто, а вот
    # обрубленный на полуслове ответ от нехватки токенов уже не почистить.
    answer = await _ask_checked(system, user_text, MODEL_SONNET, max_tokens=400 if simple else 1536, check_latin=False)
    answer = answer.replace("**", "").replace("##", "").replace("# ", "")
    return _cap_sentences(answer, 3) if simple else answer


