async def classify_concrete_answer(step: str, text: str) -> dict:
    system = CONCRETE_ANSWER_SYSTEM.replace("{step}", step)
    try:
        raw = await _ask(system, text, MODEL_HAIKU, max_tokens=80)
        data = json.loads(_strip_code_fence(raw))
        target = data.get("target")
        if target not in ("other", "self", "unclear"):
            target = "unclear"
        return {
            "target": target,
            "concrete_behavior": bool(data.get("concrete_behavior", False)),
            "confidence": float(data.get("confidence", 0.0)),
        }
    except Exception:  # noqa: BLE001
        logger.exception("classify_concrete_answer упал/не распарсился")
        # безопасный дефолт при сбое — не блокировать разбор из-за сбоя API
        return {"target": "other", "concrete_behavior": True, "confidence": 0.0}


